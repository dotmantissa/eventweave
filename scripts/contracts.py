"""Assemble self contained contracts and check the exact deployable sources."""
from pathlib import Path
import argparse
import subprocess

ROOT = Path(__file__).resolve().parents[1]
HEADER = '# { "Depends": "py-genlayer:1jb45aa8ynh2a9c9xn3b7qqh8sm5q93hwfp7jqmwsfhh8jpz09h6" }\n'

def build(check=False):
    common = (ROOT / 'contracts/lib/common.py').read_text()
    for source in sorted((ROOT / 'contracts/src').glob('*.py')):
        output = ROOT / 'contracts/deployable' / source.name
        body = source.read_text()
        if source.stem in ('incident_history', 'release_evidence'):
            name = 'IncidentHistory' if source.stem == 'incident_history' else 'ReleaseEvidence'
            body = 'class ' + name + '(gl.Contract):\n' + (ROOT / 'contracts/lib/consumer.py').read_text() + '\n' + body
        expected = HEADER + '\n# Generated by scripts/contracts.py from contracts/lib and contracts/src.\n' + common + '\n' + body
        if check:
            if not output.exists() or output.read_text() != expected:
                raise SystemExit(f'Stale generated contract: {output.name}')
        else:
            output.write_text(expected)
    for source in sorted((ROOT / 'contracts/deployable').glob('*.py')):
        subprocess.run([str(ROOT / '.venv/bin/genvm-lint'), 'check', str(source), '--json'], check=True)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
